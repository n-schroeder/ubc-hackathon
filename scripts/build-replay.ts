// Builds the static, read-only replay of the firewall dashboard into site/ (Cloudflare Pages serves it as is).
//
//   npm run build:site [-- --data docs/rehearsal/raw] [--out site] [--env .env]
//
// Input: a recorded run's ledger.json (GET /ledger) and mandates.json (GET /mandates) in --data, plus the
// hand-written captions in packages/firewall/replay/notes.json. Output: the live dashboard's own files from
// packages/firewall/public/ (unchanged), replay.js (an in-browser stand-in for the firewall's API and its SSE
// stream, driven by a virtual clock), replay.css, and the recording as replay-data.js.
//
// The site holds no secrets and can't spend: there's no wallet, no key and no server behind it. To make sure,
// the build scans everything it wrote for the values in .env (and for key-shaped strings) and deletes the
// output if anything matches. Run it in the checkout that has the .env.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync, copyFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { parseArgs } from "node:util";
import { parse as parseDotenv } from "dotenv";
import { EXPLORER_URL, REPO_ROOT, formatUsdc, loadPolicy } from "@asf/shared";
import { deriveReplay, findLeaks, secretNeedles, type Notes } from "./lib/replay.ts";

const { values } = parseArgs({
  options: {
    data: { type: "string", default: "docs/rehearsal/raw" },
    out: { type: "string", default: "site" },
    env: { type: "string", default: ".env" },
  },
});
const dataDir = resolve(REPO_ROOT, values.data!);
const outDir = resolve(REPO_ROOT, values.out!);
const envPath = resolve(REPO_ROOT, values.env!);
const PUBLIC = resolve(REPO_ROOT, "packages/firewall/public");
const REPLAY = resolve(REPO_ROOT, "packages/firewall/replay");

function readJson(path: string): any {
  if (!existsSync(path)) {
    console.error(`missing ${relative(REPO_ROOT, path)}: export the recorded run's GET /ledger?limit=1000 and GET /mandates there (see docs/hosting.md)`);
    process.exit(1);
  }
  return JSON.parse(readFileSync(path, "utf8"));
}

// ------------------------------------------------------------------ data

const ledger = readJson(join(dataDir, "ledger.json"));
const mandates = readJson(join(dataDir, "mandates.json"));
if (!Array.isArray(ledger) || !Array.isArray(mandates)) throw new Error("ledger.json and mandates.json must be JSON arrays");
const notes = readJson(join(REPLAY, "notes.json")) as Notes;
// Same JSON the firewall's GET /policy serves (bigints as decimal USDC strings).
const policy = JSON.parse(JSON.stringify(loadPolicy(), (_k, v) => (typeof v === "bigint" ? formatUsdc(v) : v)));
const data = deriveReplay(ledger, mandates, policy, notes, EXPLORER_URL);

// ------------------------------------------------------------------ site

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
for (const f of ["app.js", "chart.js", "util.js", "styles.css"]) copyFileSync(join(PUBLIC, f), join(outDir, f));
for (const f of ["replay.js", "replay.css"]) copyFileSync(join(REPLAY, f), join(outDir, f));
writeFileSync(join(outDir, "replay-data.js"), `// Recorded firewall state for the replay (generated by scripts/build-replay.ts).\nwindow.__REPLAY__ = ${JSON.stringify(data)};\n`);

// The live index.html with the replay layer loaded before app.js (a classic script runs before a module).
let html = readFileSync(join(PUBLIC, "index.html"), "utf8");
const edits: [string, string][] = [
  ["<title>Agent Spending Firewall</title>",
    `<title>Agent Spending Firewall · replay</title>\n  <meta name="description" content="Read-only replay of a recorded Agent Spending Firewall run on Arc testnet: every decision, rule and onchain payment.">`],
  [`<link rel="stylesheet" href="styles.css">`, `<link rel="stylesheet" href="styles.css">\n  <link rel="stylesheet" href="replay.css">`],
  [`<script type="module" src="app.js"></script>`, `<script src="replay-data.js"></script>\n  <script src="replay.js"></script>\n  <script type="module" src="app.js"></script>`],
];
for (const [from, to] of edits) {
  if (!html.includes(from)) throw new Error(`packages/firewall/public/index.html no longer contains ${from}; update scripts/build-replay.ts`);
  html = html.replace(from, to);
}
writeFileSync(join(outDir, "index.html"), html);

// Cloudflare Pages response headers. connect-src 'self' also means the page can't reach a real firewall or vendor.
writeFileSync(join(outDir, "_headers"), `/*
  Content-Security-Policy: default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'
  Referrer-Policy: no-referrer
  X-Content-Type-Options: nosniff
`);

// ------------------------------------------------------------------ secret scan

const needles = existsSync(envPath) ? secretNeedles(parseDotenv(readFileSync(envPath))) : [];
if (!needles.length) console.warn(`⚠ no secrets to compare against (${relative(REPO_ROOT, envPath) || envPath} missing or empty): only the key-pattern checks ran. Build in the checkout that has the .env before publishing.`);
const files = (function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f)) : [join(dir, f)]));
})(outDir);
const leaks = files.flatMap((f) => findLeaks(readFileSync(f, "utf8"), needles).map((what) => `${relative(REPO_ROOT, f)}: ${what}`));
if (leaks.length) {
  rmSync(outDir, { recursive: true, force: true });
  console.error(`✘ secret scan failed, deleted ${relative(REPO_ROOT, outDir)}/:\n  ${leaks.join("\n  ")}`);
  process.exit(1);
}

const kb = Math.round(files.reduce((a, f) => a + statSync(f).size, 0) / 1024);
const m = data.meta;
console.log(`✔ built ${relative(REPO_ROOT, outDir)}/ (${files.length} files, ${kb} KB) from ${relative(REPO_ROOT, dataDir)}/`);
console.log(`  ${data.takes.length} takes · ${m.rows} decisions (${m.approved} paid, ${m.denied} denied) · $${m.spent} spent · ${m.explorerLinks} explorer links`);
console.log(`  ${data.takes.map((t) => `${t.id}${t.scene ? "" : " (unmatched task)"}`).join(" ")}`);
console.log(`  secret scan: clean (${needles.length} .env values + key patterns, ${files.length} files)`);
if (m.explorerLinks < m.approved) console.log(`  note: ${m.approved - m.explorerLinks} paid rows have no explorer link yet (Gateway settles in batches); re-export the ledger later for more`);
console.log(`  preview: python3 -m http.server -d ${relative(REPO_ROOT, outDir)} 8788  ·  publish: docs/hosting.md`);
