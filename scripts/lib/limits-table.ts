// Renders the README's safety-limits tables from config/policy.json and config/registry.json, so the
// numbers in the README are the numbers the firewall enforces. `npm run docs:limits` rewrites the block
// between the markers; a test (scripts/test/readme-limits.test.ts) fails if it is out of date.
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { REPO_ROOT, short } from "@asf/shared";

export const START = "<!-- limits:start (generated by `npm run docs:limits` from config/*.json; do not edit by hand) -->";
export const END = "<!-- limits:end -->";

type RawPolicy = {
  perCallMax: string;
  perTransferCap: string;
  humanApprovalAbove: string;
  dailyBudget: string;
  recipientAllowlist: string[];
  mandateDefaults: { budget: string; ttlSeconds: number };
  preflight: { maxDriftPct: number };
  velocity: {
    perMinute: string;
    maxCallsPerServicePerTask: number;
    duplicateLimit: number;
    duplicateWindowSeconds: number;
    noProgressLimit: number;
  };
};
type RawService = { id: string; expectedPrice: string; priceTolerancePct: number; payTo: string };

const readJson = <T>(file: string): T => JSON.parse(readFileSync(resolve(REPO_ROOT, file), "utf8")) as T;
const usd = (s: string) => `$${s}`;
const code = (s: string | number) => `\`${s}\``;

/** Price band upper bound, in exact decimal arithmetic on 6-decimal base units (no floats). */
function bandMax(price: string, pct: number): string {
  const [whole, frac = ""] = price.split(".");
  const units = BigInt(whole!) * 1_000_000n + BigInt(frac.padEnd(6, "0").slice(0, 6));
  const max = (units * BigInt(100 + pct)) / 100n;
  const f = (max % 1_000_000n).toString().padStart(6, "0").replace(/0+$/, "");
  return `${max / 1_000_000n}${f ? `.${f}` : ""}`;
}

export function renderLimits(
  p: RawPolicy = readJson<RawPolicy>("config/policy.json"),
  services: RawService[] = readJson<{ services: RawService[] }>("config/registry.json").services,
): string {
  const v = p.velocity;
  const mins = p.mandateDefaults.ttlSeconds / 60;
  const ttl = `${p.mandateDefaults.ttlSeconds} s${Number.isInteger(mins) ? ` (${mins} min)` : ""}`;
  const allow = p.recipientAllowlist.map((a) => code(short(a))).join(", ") || "empty";
  const rows: [string, string, string, string][] = [
    ["Per paid API call (x402)", usd(p.perCallMax), "policy.per_call_max", "Deny any single nanopayment quote above this."],
    ["Per direct transfer", usd(p.perTransferCap), "policy.per_tx_cap", "Deny any `send_payment` above this."],
    ["Recipient allowlist", allow, "policy.recipient_not_allowed", "Direct transfers may only go to these addresses."],
    ["Daily budget (rolling 24 h)", usd(p.dailyBudget), "policy.daily_budget", "Deny once total spend in the last 24 h would pass this."],
    ["Human approval above", usd(p.humanApprovalAbove), "escalation.over_threshold", "Hold the payment in the approval queue until a human approves or denies it on the dashboard."],
    ["Task mandate budget (default)", usd(p.mandateDefaults.budget), "mandate.budget_exceeded", "Each task gets its own budget; nothing outside it can be spent."],
    ["Task mandate lifetime (default)", ttl, "mandate.none_active", "After expiry, or when the task ends, the agent has zero spending authority."],
    ["Price drift", `+${p.preflight.maxDriftPct}%`, "preflight.price_drift", "Deny a quote more than this above the last price paid to the same service."],
    ["Spend rate", `${usd(v.perMinute)} / min`, "velocity.per_minute", "Trips the breaker: all spending stops until a human resets it."],
    ["Calls per service per task", String(v.maxCallsPerServicePerTask), "velocity.calls_per_service", `Trips the breaker on paid call ${v.maxCallsPerServicePerTask + 1} to one service in one task.`],
    ["Identical requests", `${v.duplicateLimit} per ${v.duplicateWindowSeconds} s`, "velocity.duplicate", `Trips the breaker on identical paid request no. ${v.duplicateLimit + 1} inside the window (a retry loop).`],
    ["Paid calls without task progress", String(v.noProgressLimit), "velocity.no_progress", `Trips the breaker on the next paid call after ${v.noProgressLimit} in a row that didn't move the task forward (progress is counted by the harness, not reported by the model).`],
  ];
  const svc = services.map((s) =>
    `| ${code(s.id)} | ${usd(s.expectedPrice)} | +${s.priceTolerancePct}% → max ${usd(bandMax(s.expectedPrice, s.priceTolerancePct))} | ${code(short(s.payTo))} |`);
  return [
    START,
    "From [`config/policy.json`](config/policy.json):",
    "",
    "| Limit | Value | Rule id when it fires | Effect |",
    "|---|---|---|---|",
    ...rows.map(([a, b, c, d]) => `| ${a} | ${b} | ${code(c)} | ${d} |`),
    "",
    "Price bands and pinned payees, from [`config/registry.json`](config/registry.json) (`preflight.price_out_of_band`, `preflight.payto_mismatch`):",
    "",
    "| Service | Expected price | Band | Pinned `payTo` |",
    "|---|---|---|---|",
    ...svc,
    END,
  ].join("\n");
}

/** README text with the generated block replaced. Throws if the markers are missing. */
export function withLimits(readme: string, block = renderLimits()): string {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error("README.md has no limits:start / limits:end markers");
  return readme.slice(0, a) + block + readme.slice(b + END.length);
}
