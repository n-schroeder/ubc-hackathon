// Makes the watchdog webhook (port 4023, POST /quicknode) reachable from the internet, so the QuickNode
// Stream can deliver to it. Only this port is ever tunnelled; the firewall's agent and admin API on 4020
// never are. See README "Watchdog (QuickNode Streams)".
//
//   npm run tunnel
//
// With WATCHDOG_TUNNEL (a named Cloudflare Tunnel) and WATCHDOG_PUBLIC_URL (its hostname) in .env, it runs
// that tunnel. The URL stays the same on every run, so the Stream's destination never needs changing.
// The generated ingress forwards only /quicknode on that hostname, and Cloudflare answers 404 to
// everything else before it reaches this machine. One-time setup (credentials stay in ~/.cloudflared):
//
//   cloudflared tunnel login
//   cloudflared tunnel create agent-firewall
//   cloudflared tunnel route dns agent-firewall firewall.example.dev
//
// Without them it falls back to a quick tunnel on a random trycloudflare.com URL that changes every run:
//
//   cloudflared tunnel --url http://127.0.0.1:4023
import { spawn } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { REPO_ROOT, optionalEnv } from "@asf/shared";

const port = Number(optionalEnv("WATCHDOG_PORT", "4023"));
const origin = `http://127.0.0.1:${port}`;
const name = optionalEnv("WATCHDOG_TUNNEL");
const publicUrl = optionalEnv("WATCHDOG_PUBLIC_URL");

let args: string[];
if (name && publicUrl) {
  const hostname = new URL(publicUrl).hostname;
  const config = resolve(REPO_ROOT, "data/cloudflared.yml");
  mkdirSync(resolve(config, ".."), { recursive: true });
  writeFileSync(
    config,
    `# Generated by npm run tunnel. Credentials are read from ~/.cloudflared/<tunnel id>.json, never from the repo.
tunnel: ${name}
ingress:
  - hostname: ${hostname}
    path: ^/quicknode$
    service: ${origin}
  - service: http_status:404
`,
  );
  console.log(`named tunnel "${name}": https://${hostname}/quicknode -> ${origin}/quicknode (everything else: 404)`);
  args = ["tunnel", "--no-autoupdate", "--config", config, "run", name];
} else {
  console.log(`quick tunnel -> ${origin} (random URL; set WATCHDOG_TUNNEL and WATCHDOG_PUBLIC_URL for a stable one)`);
  args = ["tunnel", "--no-autoupdate", "--url", origin];
}

const child = spawn("cloudflared", args, { stdio: "inherit" });
child.on("error", (e: NodeJS.ErrnoException) => {
  console.error(e.code === "ENOENT" ? "cloudflared is not installed: https://developers.cloudflare.com/cloudflare-one/connections/connect-networks/downloads/" : e.message);
  process.exit(1);
});
child.on("exit", (code, signal) => process.exit(signal ? 0 : (code ?? 0)));
for (const sig of ["SIGINT", "SIGTERM"] as const) process.on(sig, () => child.kill(sig));
